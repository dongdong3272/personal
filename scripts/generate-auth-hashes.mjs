import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");

const QUESTION_IDS = [
  "birthday",
  "hometown",
  "favorite_movie",
  "favorite_game",
];

function loadEnvFile(relativePath) {
  const full = path.join(root, relativePath);
  if (!existsSync(full)) {
    return {};
  }
  const out = {};
  for (const line of readFileSync(full, "utf8").split("\n")) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) {
      continue;
    }
    const eq = trimmed.indexOf("=");
    if (eq === -1) {
      continue;
    }
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    out[key] = value;
  }
  return out;
}

function normalizeBirthday(value) {
  const trimmed = value.trim();
  const iso = trimmed.match(/^(\d{4})-(\d{1,2})-(\d{1,2})$/);
  if (iso) {
    const month = parseInt(iso[2], 10);
    const day = parseInt(iso[3], 10);
    if (month >= 1 && month <= 12 && day >= 1 && day <= 31) {
      return `${String(month).padStart(2, "0")}-${String(day).padStart(2, "0")}`;
    }
  }
  const monthDay = trimmed.match(/^(\d{1,2})-(\d{1,2})$/);
  if (monthDay) {
    const month = parseInt(monthDay[1], 10);
    const day = parseInt(monthDay[2], 10);
    if (month >= 1 && month <= 12 && day >= 1 && day <= 31) {
      return `${String(month).padStart(2, "0")}-${String(day).padStart(2, "0")}`;
    }
  }
  return trimmed;
}

function normalizeHometown(value) {
  return value.trim().toLowerCase().replace(/\s+/g, " ");
}

function hashAnswer(pepper, questionId, normalizedValue) {
  const payload = `${pepper}|${questionId}|${normalizedValue}`;
  return createHash("sha256").update(payload, "utf8").digest("hex");
}

const env = {
  ...loadEnvFile(".env.auth"),
  ...loadEnvFile(".env.auth.local"),
};

for (const key of [
  "AUTH_PEPPER",
  "AUTH_BIRTHDAY",
  "AUTH_HOMETOWN",
  "AUTH_MOVIE_OPTION_ID",
  "AUTH_GAME_OPTION_ID",
]) {
  if (process.env[key]) {
    env[key] = process.env[key];
  }
}

const pepper = env.AUTH_PEPPER;
const birthday = env.AUTH_BIRTHDAY;
const hometown = env.AUTH_HOMETOWN;
const movieId = env.AUTH_MOVIE_OPTION_ID;
const gameId = env.AUTH_GAME_OPTION_ID;

const missing = [];
if (!pepper) missing.push("AUTH_PEPPER");
if (!birthday) missing.push("AUTH_BIRTHDAY");
if (!hometown) missing.push("AUTH_HOMETOWN");
if (!movieId) missing.push("AUTH_MOVIE_OPTION_ID");
if (!gameId) missing.push("AUTH_GAME_OPTION_ID");

if (missing.length > 0) {
  console.error(
    `Missing required env vars: ${missing.join(", ")}.\nCopy .env.auth.example → .env.auth and fill in real values.`,
  );
  process.exit(1);
}

const values = {
  birthday: normalizeBirthday(birthday),
  hometown: normalizeHometown(hometown),
  favorite_movie: movieId.trim(),
  favorite_game: gameId.trim(),
};

const hashes = {};
for (const questionId of QUESTION_IDS) {
  hashes[questionId] = hashAnswer(pepper, questionId, values[questionId]);
}

const outPath = path.join(root, "src", "config", "authHashes.generated.ts");
const lines = [
  "// Generated by npm run auth:hash — do not edit by hand.",
  "",
  "export type AuthQuestionId =",
  '  | "birthday"',
  '  | "hometown"',
  '  | "favorite_movie"',
  '  | "favorite_game";',
  "",
  `export const AUTH_PEPPER = ${JSON.stringify(pepper)};`,
  "",
  "export const AUTH_HASHES: Record<AuthQuestionId, string> = {",
  ...QUESTION_IDS.map(
    (id) => `  ${id}: ${JSON.stringify(hashes[id])},`,
  ),
  "};",
  "",
];

writeFileSync(outPath, lines.join("\n"), "utf8");
console.log(`Wrote ${outPath}`);